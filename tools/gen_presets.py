#!/usr/bin/env python3
"""Reads the preset table in Source/Params.h and writes a JUCE-free header for Tests/PresetAudit.cpp.

Usage: python3 tools/gen_presets.py Source/Params.h out/PresetsGenerated.h
"""
import re, sys

src = open(sys.argv[1]).read()

# defaults, as in createParameterLayout()
DEF = dict(aOn=1, aType=2, aTime=420, aFeedback=0.45, aMix=0.4, aTone=0.55, aLowCut=120, aDuck=0.15, aVoice=0, aToneMode=0, aSubdiv=0, aPing=0,
           bOn=0, bType=5, bTime=380, bFeedback=0.4, bMix=0.38, bTone=0.6, bLowCut=120, bDuck=0.2, bVoice=0, bToneMode=0, bSubdiv=2, bPing=1,
           rOn=1, rType=1, rDecay=0.55, rPreDelay=40, rMix=0.36, rShimmer=0, rTone=0.55, rLowCut=180, rVoice=0, rToneMode=0,
           route=0, loopPos=2, loopLevel=0.75, bpm=112)

def parse_map(text):
    return {k: float(v.rstrip('f')) for k, v in re.findall(r'\{\s*(\w+),\s*(-?[\d.]+f?)\s*\}', text)}

presets = []
body = src[src.index('factoryPresets()'):]
for line in body.splitlines():
    line = line.strip()
    m = re.match(r'v\.push_back \(om \("([^"]+)",\s*(.*)\)\);$', line)
    if m:
        name, rest = m.group(1), m.group(2)
        extra = {}
        if '{' in rest:
            rest, mp = rest.split('{', 1)
            extra = parse_map('{' + mp)
        args = [a.strip() for a in rest.split(',') if a.strip()]
        r, a, b, ams, bms = (float(x) for x in args[:5])
        rev = args[5] != 'false' if len(args) > 5 else True
        dly = args[6] != 'false' if len(args) > 6 else True
        v = dict(rType=r, rOn=1 if rev else 0, aType=a, bType=b, aOn=1 if dly else 0, bOn=1 if dly else 0,
                 aSubdiv=0, bSubdiv=0, aTime=ams, bTime=bms, bPing=0)
        v.update(extra)
        presets.append((name, v))
        continue
    m = re.match(r'v\.push_back \(\{ "([^"]+)", "[^"]*", (\{.*\}) \}\);$', line)
    if m:
        presets.append((m.group(1), parse_map(m.group(2))))

SUB = [0, 1, 0.75, 0.5, 1/3, 0.25, 2]
def F(x): return repr(float(x)) + 'f'
out = ['// Generated by tools/gen_presets.py from Source/Params.h. Do not edit.', '#pragma once', '#include "Engine.h"',
       'struct GenPreset { const char* name; kdd::EngineParams p; };', 'inline std::vector<GenPreset> genPresets()', '{', '    std::vector<GenPreset> v;']
for name, vals in presets:
    d = dict(DEF); d.update(vals)
    beat = 60000.0 / d['bpm']
    def t(m):
        s = int(d[m + 'Subdiv'])
        return d[m + 'Time'] if s == 0 else min(2000.0, max(10.0, beat * SUB[s]))
    L = ['    {', '        kdd::EngineParams p;']
    for m in 'ab':
        L += [f'        p.{m}.on = {str(bool(d[m+"On"])).lower()}; p.{m}.position = {int(d[m+"Type"])}; p.{m}.timeMs = {F(t(m))};',
              f'        p.{m}.feedback = {F(d[m+"Feedback"])}; p.{m}.tone = {F(d[m+"Tone"])}; p.{m}.toneMode = {int(d[m+"ToneMode"])}; p.{m}.lowCutHz = {F(d[m+"LowCut"])};',
              f'        p.{m}.duck = {F(d[m+"Duck"])}; p.{m}.mk1 = {str(d[m+"Voice"] > 0.5).lower()}; p.{m}.pingPong = {str(d[m+"Ping"] > 0.5).lower()};']
    L += [f'        p.r.on = {str(bool(d["rOn"])).lower()}; p.r.position = {int(d["rType"])}; p.r.decay = {F(d["rDecay"])}; p.r.preDelayMs = {F(d["rPreDelay"])};',
          f'        p.r.shimmer = {F(d["rShimmer"])}; p.r.tone = {F(d["rTone"])}; p.r.toneMode = {int(d["rToneMode"])}; p.r.lowCutHz = {F(d["rLowCut"])}; p.r.mk1 = {str(d["rVoice"] > 0.5).lower()};',
          f'        p.mixA = {F(d["aMix"])}; p.mixB = {F(d["bMix"])}; p.mixR = {F(d["rMix"])}; p.route = {int(d["route"])};',
          f'        v.push_back ({{ "{name}", p }});', '    }']
    out += L
out += ['    return v;', '}']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(presets), 'presets')
